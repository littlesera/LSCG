// Re-records which corpus lines/conversations currently fail into test/corpus/speech/baseline-gaps.ts.
// Run after growing the corpus; review the diff before committing (every entry is a real miss).
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const file = "test/corpus/speech/baseline-gaps.ts";
const empty = `export const BASELINE_GAP_TEXTS = new Set<string>([]);
export const BASELINE_GAP_CONVERSATIONS = new Set<string>([]);
`;
writeFileSync(file, empty);
const out = ".vitest/json/baseline.json";
spawnSync("npx", ["vitest", "run", "--project", "unit", "test/corpus/speech/corpus.test.ts", "--reporter=json", `--outputFile=${out}`], { stdio: "ignore", shell: true });
const results = JSON.parse(readFileSync(out, "utf8")).testResults[0].assertionResults.filter(t => t.status === "failed" && t.ancestorTitles[2] !== "known gaps");
const texts = new Set(), convs = new Set();
for (const t of results) {
	if (t.ancestorTitles[1] === "lines") texts.add(t.title.replace(/^\[[^\]]*\] /, ""));
	else if (t.ancestorTitles[1] === "conversations") convs.add(t.title);
}
const fmt = set => [...set].sort().map(s => `\t${JSON.stringify(s)},`).join("\n");
writeFileSync(file, `// Generated by scripts/speech-baseline.mjs -- lines/conversations the module currently gets wrong.
export const BASELINE_GAP_TEXTS = new Set<string>([
${fmt(texts)}
]);
export const BASELINE_GAP_CONVERSATIONS = new Set<string>([
${fmt(convs)}
]);
`);
console.log(`${texts.size} lines and ${convs.size} conversations recorded as gaps`);
